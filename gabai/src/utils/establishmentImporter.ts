/**
 * Searches real-world places and establishments via OpenStreetMap Nominatim Geocoding API
 */
export async function searchRealWorldPlaces(
  query: string,
  nearLat?: number,
  nearLng?: number
): Promise<Array<{ name: string; address: string; lat: number; lng: number; type: string }>> {
  if (!query || query.trim().length < 2) return []

  try {
    const controller = new AbortController()
    const timeoutId = setTimeout(() => controller.abort(), 4000)

    let url = `https://nominatim.openstreetmap.org/search?format=json&q=${encodeURIComponent(
      query
    )}&countrycodes=ph&limit=12&addressdetails=1`

    if (nearLat && nearLng) {
      const delta = 0.8
      url += `&viewbox=${nearLng - delta},${nearLat + delta},${nearLng + delta},${nearLat - delta}`
    }

    const res = await fetch(url, {
      signal: controller.signal,
      headers: { 'Accept-Language': 'en,fil' },
    })
    clearTimeout(timeoutId)

    if (!res.ok) return []
    const data = await res.json()

    return data.map((item: any) => ({
      name: item.display_name.split(',')[0],
      address: item.display_name,
      lat: parseFloat(item.lat),
      lng: parseFloat(item.lon),
      type: item.type || 'place',
    }))
  } catch (err) {
    console.warn('Nominatim real search fallback:', err)
    return []
  }
}

/**
 * Returns the comprehensive Pampanga province-wide master dataset with accurate distances from user's current GPS coordinates
 */
export function getContextualEstablishments(userLat: number, userLng: number, _locationName?: string): Establishment[] {
  return PAMPANGA_MASTER_ESTABLISHMENTS.map((item, idx) => {
    const distKm = calculateDistanceKm(userLat, userLng, item.lat, item.lng)
    const conf = CATEGORY_CONFIG[item.category]

    return {
      id: `pampanga-est-${idx + 1}`,
      name: item.name,
      category: item.category,
      categoryLabel:
        item.facilityType === 'rhu_clinic'
          ? 'Rural Health Unit & Clinic'
          : item.facilityType === 'maternity_lyingin'
          ? 'Maternity & Lying-in Clinic'
          : item.facilityType === 'dialysis_center'
          ? 'Dialysis & Renal Center'
          : conf.label,
      emoji: item.category === 'hospital' && item.facilityType === 'rhu_clinic' ? '🩺' : conf.emoji,
      lat: item.lat,
      lng: item.lng,
      distance: formatDistance(distKm),
      address: item.address,
      status: item.status,
      phone: item.phone,
      capacityInfo: item.capacityInfo,
      isEvacuationCenter: item.isEvacuationCenter,
      bedCapacity: item.bedCapacity,
      hasER: item.hasER,
      municipality: item.municipality,
      facilityType: item.facilityType,
    }
  })
}

